// Builds TEST_VECTORS.md and <vectorsDir>/<suite>.json from recorded runs of the ORIGINAL app
// (<runsDir>/run-<suite>.json written by run-cases). Vectors carry observed behavior only:
// input tokens in, normalized readouts out. Harness errors are excluded and listed.
// Usage: node build-vectors.mjs <runsDir> <vectorsDir> <TEST_VECTORS.md> [normalize.json] [suite ...]
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { loadConfig, normalizedValues, readJson } from './normalize.mjs';

const [runsDir, vectorsDir, mdPath, cfgPath, ...only] = process.argv.slice(2);
if (!runsDir || !vectorsDir || !mdPath) {
  console.error('usage: node build-vectors.mjs <runsDir> <vectorsDir> <TEST_VECTORS.md> [normalize.json] [suite ...]');
  process.exit(2);
}
const cfg = loadConfig(cfgPath && cfgPath !== '-' ? cfgPath : null);
const suites = readdirSync(runsDir)
  .filter((f) => /^run-.+\.json$/.test(f))
  .map((f) => f.slice(4, -5))
  .filter((s) => !only.length || only.includes(s))
  .sort();

mkdirSync(vectorsDir, { recursive: true });
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
const sections = [];
const excluded = [];
let total = 0;

for (const suite of suites) {
  const run = readJson(join(runsDir, `run-${suite}.json`));
  const vectors = [];
  for (const c of run.cases) {
    if (c.error) { excluded.push(`${c.id} (${String(c.error).slice(0, 70)})`); continue; }
    const expect = normalizedValues(cfg, c.values ?? c.extra ?? {});
    // reads (web runner) lets a replay ask for the same readouts, including ones the original lacked
    vectors.push({ id: c.id, mode: c.mode ?? null, keys: c.steps, reset: c.reset ?? 'clear', ...(c.reads?.length ? { reads: c.reads } : {}), expect });
  }
  writeFileSync(join(vectorsDir, `${suite}.json`), JSON.stringify(vectors, null, 2));
  total += vectors.length;
  sections.push(`## ${suite} (${vectors.length})`, '', `Captured ${run.captured}, locale ${run.locale ?? '?'}`, '',
    '| id | mode | keys | observed |', '|---|---|---|---|');
  for (const v of vectors) {
    const obs = Object.entries(v.expect).map(([k, x]) => `${k}=${x}`).join('; ');
    const keys = Array.isArray(v.keys) ? v.keys.join(' ; ') : v.keys;
    sections.push(`| ${v.id} | ${v.mode ?? ''} | \`${esc(keys)}\` | ${esc(obs)} |`);
  }
  sections.push('');
}

writeFileSync(mdPath, [
  '# TEST_VECTORS', '',
  'Generated by `build-vectors.mjs` from black-box runs of the original app. Every vector is an',
  'automated test of the rebuild (JSON copies in the vectors directory). Keys use the token',
  'vocabulary defined in CLONE_SPEC.md; readouts are normalized as configured.', '',
  `Total vectors: **${total}**. Excluded harness errors (${excluded.length}): ${excluded.length ? excluded.join('; ') : 'none'}.`, '',
  ...sections,
].join('\n'));
console.log(`vectors: ${total} in ${suites.length} suites; excluded harness errors: ${excluded.length}`);
